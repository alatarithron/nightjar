#!/usr/bin/env bash
# Generates src/layers/icons.generated.css from src/icons/*.svg.
#
#   bin/build-icons.sh
#
# Why this step exists — a platform fact, not a preference:
#
#   Gecko resolves a relative url() inside a custom property against the
#   stylesheet that *uses* the var(), not the one that declares it. Thunderbird
#   consumes --icon-* from chrome://messenger/skin/*.css, so a relative path
#   written here would resolve against chrome://messenger/skin/ and fail to
#   load, rendering a blank icon. Verified with a controlled Gecko test; see
#   .agents/decisions/004-icons-as-data-uris.md.
#
# A data: URI carries no base, so it resolves identically from any sheet and
# stays portable across machines. Each src/icons/<name>.svg becomes
# --icon-<name>.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

OUT="src/layers/icons.generated.css"
SRC_DIR="src/icons"

if ! command -v python3 >/dev/null 2>&1; then
  echo "error: python3 is required to URL-encode the SVGs" >&2
  exit 1
fi

{
  echo "/* Generated by bin/build-icons.sh — do not edit."
  echo " *"
  echo " * Each icon is inlined as a data: URI because Gecko resolves relative URLs"
  echo " * in custom properties against the consuming stylesheet, which for these"
  echo " * properties is chrome://messenger/skin/. See decision 004."
  echo " *"
  echo " * Edit the artwork in $SRC_DIR/ and re-run the script."
  echo " */"
  echo
  echo ":root {"

  found=0
  while IFS= read -r svg; do
    [ -n "$svg" ] || continue
    name="$(basename "$svg" .svg)"
    encoded="$(python3 - "$svg" <<'PY'
import re, sys, urllib.parse
raw = open(sys.argv[1], encoding="utf-8").read()
# Drop comments and collapse whitespace: the payload travels in every icon.
raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)
raw = re.sub(r"\s+", " ", raw).strip()
# Encode everything CSS or the URL parser could misread. Leave the structural
# characters that are safe in a url("...") token readable.
print(urllib.parse.quote(raw, safe="/:=<>' "))
PY
)"
    printf '  --icon-%s: url("data:image/svg+xml,%s") !important;\n' "$name" "$encoded"
    found=$((found + 1))
  done <<< "$(find "$SRC_DIR" -name '*.svg' | sort)"

  echo "}"
} > "$OUT"

echo "wrote $OUT ($(find "$SRC_DIR" -name '*.svg' | wc -l) icons)"
