#!/usr/bin/env bash
# Regenerates docs/thunderbird-tokens.md from the installed Thunderbird.
#
#   bin/dump-tb-reference.sh [path/to/omni.ja]
#
# The reference is the authoritative list of custom properties Nightjar is
# allowed to override. Re-run after every Thunderbird upgrade: tokens are
# internal API and do get renamed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/docs/thunderbird-tokens.md"

OMNI="${1:-}"
if [ -z "$OMNI" ]; then
  for candidate in /usr/lib/thunderbird/omni.ja /usr/lib64/thunderbird/omni.ja \
                   /opt/thunderbird/omni.ja "$HOME/.local/share/thunderbird/omni.ja"; do
    [ -f "$candidate" ] && { OMNI="$candidate"; break; }
  done
fi
if [ -z "$OMNI" ] || [ ! -f "$OMNI" ]; then
  echo "error: omni.ja not found; pass it as an argument" >&2
  exit 1
fi
if ! command -v unzip >/dev/null 2>&1; then
  echo "error: unzip is required" >&2
  exit 1
fi

version=""
app_ini="$(dirname "$OMNI")/application.ini"
if [ -f "$app_ini" ]; then
  version="$(awk -F= '/^Version=/{print $2; exit}' "$app_ini")"
fi

SKIN="chrome/classic/skin/classic/messenger"

read_css() { unzip -p "$OMNI" "$SKIN/$1" 2>/dev/null; }

# Thunderbird is not consistent about case: the messenger skin is kebab-case
# throughout, and the calendar package declares a camelCase `--view*` family.
# A lowercase-only character class silently dropped all thirty of them.
names() { grep -oE '^[[:space:]]*--[A-Za-z0-9-]+' | tr -d ' \t' | sort -u; }

# Every custom property *read* anywhere in the application, not just in the
# messenger skin: a token declared by the skin is often consumed by the toolkit,
# and JavaScript sets some of them by name through setProperty. Scoping this to
# the skin alone reports tokens as dead that are merely consumed elsewhere.
all_consumed() {
  { unzip -p "$OMNI" '*.css' 2>/dev/null | grep -oE 'var\([[:space:]]*--[A-Za-z0-9-]+'
    unzip -p "$OMNI" '*.js' '*.mjs' '*.xhtml' 2>/dev/null | grep -oE -- '--[A-Za-z0-9-]+'
  } | grep -oE -- '--[A-Za-z0-9-]+' | sort -u
}

# The element ids and custom-element names `src/` selects on. `bin/check.sh`
# derives the same two lists the same way; keep them in step.
#
# palette.css is excluded because a hex color is indistinguishable from an id by
# shape. It holds nothing but colors, which is enforced separately.
nightjar_ids() {
  find "$ROOT/src" -name '*.css' ! -name 'palette.css' -print0 \
    | xargs -0 grep -hoE '#[A-Za-z][A-Za-z0-9_-]*' 2>/dev/null | sort -u
}

# Custom elements are the only element names worth checking: an HTML or XUL tag
# is guaranteed by the platform, while unified-toolbar is Thunderbird's own and
# can be renamed. A custom element always contains a dash, which is what makes
# it recognizable at the head of a selector.
#
# The name is taken up to the first character that cannot be part of it, rather
# than requiring a brace or comma next: `notification-message[type="warning"]`
# is a selector too, and demanding `{` silently skipped it — which looks exactly
# like the check passing.
nightjar_elements() {
  find "$ROOT/src" -name '*.css' -print0 \
    | xargs -0 grep -hoE '^[a-z][a-z0-9]*(-[a-z0-9]+)+[^A-Za-z0-9-]' 2>/dev/null \
    | grep -oE '^[a-z0-9-]+' | sort -u
}

# Every id Thunderbird's own documents and scripts define. Both spellings count:
# most ids are attributes in markup, a few are only ever handed to
# getElementById.
tb_ids() {
  unzip -p "$OMNI" '*.xhtml' '*.html' '*.js' '*.mjs' 2>/dev/null \
    | grep -oE '(id="[A-Za-z][A-Za-z0-9_-]*"|getElementById\("[A-Za-z][A-Za-z0-9_-]*")' \
    | grep -oE '"[A-Za-z][A-Za-z0-9_-]*"' | tr -d '"' | sort -u
}

tb_elements() {
  unzip -p "$OMNI" '*.xhtml' '*.html' '*.js' '*.mjs' 2>/dev/null \
    | grep -oE '(customElements\.define\("[a-z0-9]+(-[a-z0-9]+)+"|<(html:)?[a-z0-9]+(-[a-z0-9]+)+[[:space:]>/])' \
    | grep -oE '[a-z0-9]+(-[a-z0-9]+)+' | sort -u
}

# Every custom property Thunderbird declares, in the skin *and* in the content
# directory. The trailing colon is what separates a declaration from a var()
# reference, which is followed by ')' or ','.
#
# The messenger skin was the only source at first, and each addition came from a
# surface that could not be themed because its names were refused as invented:
# the About dialog declares its colors under chrome://messenger/content/, and the
# calendar has a package of its own with a ~30-strong `--view*` family under
# chrome://calendar/skin/. "The skin" was never the boundary; it was just where
# this script happened to look.
all_declared() {
  unzip -p "$OMNI" "$SKIN/*.css" "chrome/messenger/content/*.css" \
                   "chrome/calendar/skin/*.css" 2>/dev/null \
    | grep -oE '(^|[[:space:]{;])--[A-Za-z0-9-]+[[:space:]]*:' \
    | grep -oE -- '--[A-Za-z0-9-]+' | sort -u
}

{
  echo "# Thunderbird custom-property reference"
  echo
  echo "Generated by \`bin/dump-tb-reference.sh\` from \`$OMNI\`${version:+ (Thunderbird $version)}."
  echo "Do not edit by hand. Re-run after upgrading Thunderbird."
  echo
  echo "Only properties listed here exist. Overriding anything else in"
  echo "\`src/\` is a silent no-op. The list covers every custom property declared"
  echo "under \`chrome://messenger/skin/\`, \`chrome://messenger/content/\` and"
  echo "\`chrome://calendar/skin/\`, grouped by how good an override surface each"
  echo "one is."
  echo

  echo "## Icon properties"
  echo
  echo "Declared on \`:root\` in \`chrome://messenger/skin/icons.css\`. Redefining one"
  echo "replaces that icon everywhere. See \`src/layers/icons.css\` for the artwork rules."
  echo
  echo '```css'
  read_css "icons.css" | names
  echo '```'
  echo

  echo "## Semantic properties"
  echo
  echo "Declared in \`chrome://messenger/skin/shared/variables.css\`. These are the"
  echo "preferred override surface: they survive internal refactors better than selectors."
  echo
  echo '```css'
  read_css "shared/variables.css" | names
  echo '```'
  echo

  echo "## Folder colors"
  echo
  echo "Declared on \`:root\` in \`chrome://messenger/skin/folderColors.css\` and consumed"
  echo "by the folder pane as \`--icon-color\`, which feeds both context tones."
  echo
  echo "These are the **default** colors only. A color the user picks for a folder, and"
  echo "a tag color, are applied by \`about3Pane.js\` as an inline style on the row"
  echo "(\`row.icon.style.setProperty(\"--icon-color\", …)\`), and an inline style wins over"
  echo "any stylesheet. The inbox additionally prefers \`--account-color\` when set."
  echo "Overriding the tokens below therefore restyles the defaults without taking the"
  echo "user's choice away."
  echo
  echo '```css'
  read_css "folderColors.css" | names
  echo '```'
  echo

  echo "## Color primitives"
  echo
  echo "Declared in \`chrome://messenger/skin/colors.css\`. Two different kinds of"
  echo "thing share this file, and they are not interchangeable."
  echo
  echo "The **raw scale** — \`--color-blue-50\`, \`--color-gray-70\`, \`--color-ink-40\` —"
  echo "is not overridden. Thunderbird's components pick from it for meaning, so"
  echo "repainting a rung changes things that were never about the theme, and the"
  echo "semantic layer that consumes it is the right place to intervene."
  echo
  echo "The **roles** — \`--color-primary-*\`, \`--color-surface-*\` — are overridden."
  echo "They behave like the semantic tokens in \`variables.css\` and merely live"
  echo "here: the primary action color and the surface ramp, read across the"
  echo "account hub, account settings, downloads, import and the calendar dialogs."
  echo
  echo '```css'
  read_css "colors.css" | names
  echo '```'
  echo

  echo "## Other component properties"
  echo
  echo "Every remaining custom property Thunderbird declares under"
  echo "\`chrome://messenger/skin/\`, \`chrome://messenger/content/\` or"
  echo "\`chrome://calendar/skin/\`. The sections"
  echo "above are the curated surfaces; this one exists so the reference is complete,"
  echo "because a name missing from this file is treated as invented by"
  echo "\`bin/check.sh\`."
  echo
  echo "Most of these are declared on a component rather than on \`:root\`. Custom"
  echo "properties inherit, so a \`:root\` override still reaches the component — but a"
  echo "local redeclaration shadows it. Prefer a semantic token when one expresses the"
  echo "same change."
  echo
  echo '```css'
  curated="$(mktemp)"
  { read_css "icons.css" | names
    read_css "shared/variables.css" | names
    read_css "folderColors.css" | names
    read_css "colors.css" | names
  } | sort -u > "$curated"
  comm -23 <(all_declared) "$curated"
  rm -f "$curated"
  echo '```'
  echo

  echo "## Declared but never consumed"
  echo
  echo "Thunderbird declares these and no stylesheet, script or document ever"
  echo "reads them. **Overriding one is a silent no-op**, exactly like inventing a"
  echo "name — the property exists, so it passes a spelling check, and still does"
  echo "nothing. \`bin/check.sh\` refuses an override that lands here."
  echo
  echo "Presence in the sections above therefore proves a name is real, not that"
  echo "it is wired to anything. Before trading a working selector for a token,"
  echo "confirm the token is not on this list."
  echo
  echo '```css'
  comm -23 <(all_declared) <(all_consumed)
  echo '```'
  echo

  echo "## Selector targets that exist"
  echo
  echo "The element ids and custom-element names \`src/\` selects on, filtered down"
  echo "to the ones Thunderbird actually has. Unlike every section above this one is"
  echo "**not** exhaustive: Thunderbird defines around eight thousand ids and listing"
  echo "them all would bury the rest of this file."
  echo
  echo "It is still a real check, because the filter runs against \`omni.ja\`, not"
  echo "against \`src/\`. A name Nightjar uses and Thunderbird does not have is simply"
  echo "never emitted, no matter how many times this script is re-run, so"
  echo "\`bin/check.sh\` can read an absence as a failure."
  echo
  echo "Selectors are the fallback when no token expresses a change, and they are"
  echo "the part of the theme an upgrade breaks first. This section does not prove"
  echo "a selector *matches* — an id can exist at a different depth than the"
  echo "combinator assumes, which is a failure only a running Thunderbird shows."
  echo
  echo '```css'
  comm -12 <(nightjar_ids | sed 's/^#//') <(tb_ids) | sed 's/^/#/'
  comm -12 <(nightjar_elements) <(tb_elements)
  echo '```'
} > "$OUT"

echo "wrote $OUT"
